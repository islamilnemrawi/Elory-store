-- Minimal disposable PostgreSQL schema for exercising the Elory inventory migration.
-- This fixture is used only by the GitHub Actions PostgreSQL service, never production.
DO $roles$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    CREATE ROLE anon NOLOGIN;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    CREATE ROLE authenticated NOLOGIN;
  END IF;
END;
$roles$;

CREATE SCHEMA IF NOT EXISTS auth;
CREATE SCHEMA IF NOT EXISTS private;

CREATE OR REPLACE FUNCTION auth.uid()
RETURNS uuid
LANGUAGE sql
STABLE
AS $function$
  SELECT NULL::uuid;
$function$;

CREATE TABLE public.products (
  id uuid PRIMARY KEY,
  stock integer NOT NULL CHECK (stock >= 0),
  active boolean NOT NULL DEFAULT true,
  price numeric NOT NULL DEFAULT 10,
  wholesale_price numeric,
  code text,
  sku text,
  name text NOT NULL DEFAULT 'Fixture product',
  image text,
  variants jsonb DEFAULT '[]'::jsonb
);

CREATE TABLE public.orders (
  id uuid PRIMARY KEY,
  order_number bigint GENERATED BY DEFAULT AS IDENTITY,
  user_id uuid,
  created_at timestamptz NOT NULL DEFAULT now(),
  status text NOT NULL,
  payment_method text,
  items jsonb NOT NULL,
  shipping_cost numeric,
  total numeric,
  governorate text,
  center text,
  customer_order_code text,
  customer_access_token text
);

CREATE OR REPLACE FUNCTION public.elory_validate_order_totals()
RETURNS trigger
LANGUAGE plpgsql
AS $function$
BEGIN
  RETURN NEW;
END;
$function$;
