-- Minimal PostgreSQL 17 fixture for product-access regression tests.
-- Uses dummy roles, accounts, products and permissions only.

DO $roles$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN CREATE ROLE anon NOLOGIN; END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN CREATE ROLE authenticated NOLOGIN; END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'service_role') THEN CREATE ROLE service_role NOLOGIN BYPASSRLS; END IF;
END;
$roles$;

CREATE SCHEMA auth;
CREATE SCHEMA private;

CREATE TABLE auth.users (id uuid PRIMARY KEY);
CREATE FUNCTION auth.uid()
RETURNS uuid
LANGUAGE sql
STABLE
AS $function$
  SELECT NULLIF(current_setting('request.jwt.claim.sub', true), '')::uuid;
$function$;

CREATE FUNCTION public.has_staff_permission(p_permission text)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO pg_catalog
AS $function$
  SELECT position(p_permission IN COALESCE(current_setting('test.permissions', true), '')) > 0;
$function$;
GRANT EXECUTE ON FUNCTION public.has_staff_permission(text) TO authenticated;

CREATE TABLE public.products (
  id uuid PRIMARY KEY,
  name text NOT NULL,
  description text,
  image text,
  category text,
  price numeric NOT NULL,
  old_price numeric,
  wholesale_price numeric,
  code text,
  stock integer,
  discount integer,
  featured boolean,
  active boolean,
  created_at timestamptz,
  colors jsonb,
  sizes jsonb,
  variants jsonb,
  sku text,
  weight numeric,
  gallery jsonb,
  color_options jsonb
);
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
GRANT SELECT ON public.products TO anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.products TO authenticated;

CREATE POLICY "Staff product select permission"
  ON public.products AS RESTRICTIVE FOR SELECT TO authenticated
  USING (public.has_staff_permission('products.view'));
CREATE POLICY "pinky_public_active_products"
  ON public.products AS PERMISSIVE FOR SELECT TO anon, authenticated
  USING (COALESCE(active, true) IS TRUE);
CREATE POLICY "staff_products_select_grant"
  ON public.products AS PERMISSIVE FOR SELECT TO authenticated
  USING (public.has_staff_permission('products.view'));

CREATE VIEW public.catalog_products
WITH (security_invoker = true)
AS
SELECT id, name, description, image, category, price, old_price, discount,
       featured, active, colors, color_options, sizes, variants, gallery, created_at
  FROM public.products
 WHERE COALESCE(active, true) IS TRUE;
GRANT SELECT ON public.catalog_products TO anon, authenticated;

CREATE TABLE public.coupons (
  id uuid PRIMARY KEY,
  code text NOT NULL,
  active boolean NOT NULL DEFAULT true
);
ALTER TABLE public.coupons ENABLE ROW LEVEL SECURITY;
GRANT SELECT ON public.coupons TO anon, authenticated;
CREATE POLICY "Public can validate coupon by code"
  ON public.coupons FOR SELECT TO anon, authenticated USING (active IS TRUE);
CREATE POLICY "Staff coupon select permission"
  ON public.coupons FOR SELECT TO authenticated
  USING (public.has_staff_permission('coupons.view') OR public.has_staff_permission('coupons.manage'));

CREATE TABLE public.owner_data_reset_settings (
  singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton IS TRUE),
  owner_id uuid REFERENCES auth.users(id)
);
CREATE TABLE public.owner_data_reset_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id uuid REFERENCES auth.users(id)
);
