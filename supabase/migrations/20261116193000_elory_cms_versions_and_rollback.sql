-- Private, staff-only published configuration snapshots for the Elory website editor.
-- Snapshot restoration deliberately preserves the CURRENT global.isStoreOpen value.

CREATE TABLE IF NOT EXISTS elory_cms_private.site_customization_versions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label text NOT NULL DEFAULT 'نسخة قبل النشر',
    config jsonb NOT NULL,
    store_settings jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by uuid DEFAULT auth.uid()
);

ALTER TABLE elory_cms_private.site_customization_versions ENABLE ROW LEVEL SECURITY;

GRANT USAGE ON SCHEMA elory_cms_private TO authenticated;
REVOKE ALL ON TABLE elory_cms_private.site_customization_versions FROM PUBLIC, anon;
GRANT SELECT, INSERT, DELETE ON TABLE elory_cms_private.site_customization_versions TO authenticated;
REVOKE ALL ON SEQUENCE elory_cms_private.site_customization_versions_id_seq FROM PUBLIC, anon;
GRANT USAGE, SELECT ON SEQUENCE elory_cms_private.site_customization_versions_id_seq TO authenticated;

DROP POLICY IF EXISTS "authorized staff manage CMS versions"
    ON elory_cms_private.site_customization_versions;

CREATE POLICY "authorized staff manage CMS versions"
    ON elory_cms_private.site_customization_versions
    FOR ALL
    TO authenticated
    USING (public.elory_can_edit_site())
    WITH CHECK (public.elory_can_edit_site());

CREATE INDEX IF NOT EXISTS site_customization_versions_created_at_idx
    ON elory_cms_private.site_customization_versions (created_at DESC, id DESC);

CREATE OR REPLACE FUNCTION public.admin_create_site_customization_snapshot(p_label text DEFAULT 'نسخة قبل النشر')
RETURNS bigint
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $function$
DECLARE
    v_config jsonb;
    v_store_settings jsonb;
    v_snapshot_id bigint;
BEGIN
    IF auth.uid() IS NULL OR NOT public.elory_can_edit_site() THEN
        RAISE EXCEPTION 'Not authorized to manage website versions' USING ERRCODE = '42501';
    END IF;

    SELECT sc.config
      INTO v_config
      FROM public.site_customizations AS sc
     WHERE sc.id = 1
     FOR UPDATE;

    IF v_config IS NULL THEN
        RAISE EXCEPTION 'Published website configuration was not found' USING ERRCODE = 'P0002';
    END IF;

    SELECT pg_catalog.to_jsonb(ss)
      INTO v_store_settings
      FROM public.store_settings AS ss
     WHERE ss.id = 1
     FOR UPDATE;

    IF v_store_settings IS NULL THEN
        RAISE EXCEPTION 'Store settings row was not found' USING ERRCODE = 'P0002';
    END IF;

    INSERT INTO elory_cms_private.site_customization_versions
        (label, config, store_settings, created_by)
    VALUES
        (
            pg_catalog.left(COALESCE(NULLIF(pg_catalog.btrim(p_label), ''), 'نسخة قبل النشر'), 120),
            v_config,
            v_store_settings,
            auth.uid()
        )
    RETURNING id INTO v_snapshot_id;

    DELETE FROM elory_cms_private.site_customization_versions AS versions
     WHERE versions.id NOT IN (
        SELECT keep_versions.id
          FROM elory_cms_private.site_customization_versions AS keep_versions
         ORDER BY keep_versions.created_at DESC, keep_versions.id DESC
         LIMIT 20
     );

    RETURN v_snapshot_id;
END;
$function$;

CREATE OR REPLACE FUNCTION public.admin_list_site_customization_versions()
RETURNS jsonb
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $function$
DECLARE
    v_versions jsonb;
BEGIN
    IF auth.uid() IS NULL OR NOT public.elory_can_edit_site() THEN
        RAISE EXCEPTION 'Not authorized to view website versions' USING ERRCODE = '42501';
    END IF;

    SELECT COALESCE(
        pg_catalog.jsonb_agg(
            pg_catalog.jsonb_build_object(
                'id', versions.id,
                'label', versions.label,
                'createdAt', versions.created_at
            )
            ORDER BY versions.created_at DESC, versions.id DESC
        ),
        '[]'::jsonb
    )
      INTO v_versions
      FROM elory_cms_private.site_customization_versions AS versions;

    RETURN v_versions;
END;
$function$;

CREATE OR REPLACE FUNCTION public.admin_restore_site_customization_version(p_version_id bigint)
RETURNS boolean
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $function$
DECLARE
    v_saved_config jsonb;
    v_saved_settings jsonb;
    v_live_config jsonb;
    v_current_store_open jsonb;
    v_updated_rows integer;
BEGIN
    IF auth.uid() IS NULL OR NOT public.elory_can_edit_site() THEN
        RAISE EXCEPTION 'Not authorized to restore website versions' USING ERRCODE = '42501';
    END IF;

    SELECT versions.config, versions.store_settings
      INTO v_saved_config, v_saved_settings
      FROM elory_cms_private.site_customization_versions AS versions
     WHERE versions.id = p_version_id;

    IF v_saved_config IS NULL OR v_saved_settings IS NULL THEN
        RAISE EXCEPTION 'Website version was not found' USING ERRCODE = 'P0002';
    END IF;

    SELECT sc.config
      INTO v_live_config
      FROM public.site_customizations AS sc
     WHERE sc.id = 1
     FOR UPDATE;

    IF v_live_config IS NULL THEN
        RAISE EXCEPTION 'Current website configuration was not found' USING ERRCODE = 'P0002';
    END IF;

    -- Save the current state before restoring, so the operation itself is reversible.
    PERFORM public.admin_create_site_customization_snapshot('نسخة تلقائية قبل الاستعادة');

    -- Preserve the live switch exactly as it is now; never restore its older snapshot value.
    v_current_store_open := v_live_config #> '{global,isStoreOpen}';
    IF pg_catalog.jsonb_typeof(v_saved_config->'global') IS DISTINCT FROM 'object' THEN
        v_saved_config := pg_catalog.jsonb_set(
            COALESCE(v_saved_config, '{}'::jsonb),
            '{global}',
            '{}'::jsonb,
            true
        );
    END IF;

    IF v_current_store_open IS NULL THEN
        v_saved_config := v_saved_config #- '{global,isStoreOpen}';
    ELSE
        v_saved_config := pg_catalog.jsonb_set(
            v_saved_config,
            '{global,isStoreOpen}',
            v_current_store_open,
            true
        );
    END IF;

    UPDATE public.site_customizations
       SET config = v_saved_config,
           updated_at = pg_catalog.now()
     WHERE id = 1;

    GET DIAGNOSTICS v_updated_rows = ROW_COUNT;
    IF v_updated_rows <> 1 THEN
        RAISE EXCEPTION 'Could not restore website customization row' USING ERRCODE = 'P0002';
    END IF;

    UPDATE public.store_settings
       SET store_name = CASE WHEN v_saved_settings ? 'store_name' THEN v_saved_settings->>'store_name' ELSE store_name END,
           whatsapp = CASE WHEN v_saved_settings ? 'whatsapp' THEN v_saved_settings->>'whatsapp' ELSE whatsapp END,
           instagram = CASE WHEN v_saved_settings ? 'instagram' THEN v_saved_settings->>'instagram' ELSE instagram END,
           facebook = CASE WHEN v_saved_settings ? 'facebook' THEN v_saved_settings->>'facebook' ELSE facebook END,
           logo = CASE WHEN v_saved_settings ? 'logo' THEN v_saved_settings->>'logo' ELSE logo END,
           updated_at = pg_catalog.now()
     WHERE id = 1;

    GET DIAGNOSTICS v_updated_rows = ROW_COUNT;
    IF v_updated_rows <> 1 THEN
        RAISE EXCEPTION 'Could not restore store settings row' USING ERRCODE = 'P0002';
    END IF;

    RETURN true;
END;
$function$;

REVOKE ALL ON FUNCTION public.admin_create_site_customization_snapshot(text) FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.admin_list_site_customization_versions() FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.admin_restore_site_customization_version(bigint) FROM PUBLIC, anon;

GRANT EXECUTE ON FUNCTION public.admin_create_site_customization_snapshot(text) TO authenticated;
GRANT EXECUTE ON FUNCTION public.admin_list_site_customization_versions() TO authenticated;
GRANT EXECUTE ON FUNCTION public.admin_restore_site_customization_version(bigint) TO authenticated;
